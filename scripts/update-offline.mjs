// Run after synchronising games or editing any runtime file.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const digest = (data) => createHash('sha256').update(data).digest('base64');
const runtime = /\.(html|webmanifest|css|js|json|svg|webp|png|jpe?g|ico|woff2?|ttf|mp3|ogg|wav)$/i;

async function walk(dir) {
  const paths = [];
  for (const item of await readdir(join(root, dir), { withFileTypes: true })) {
    const path = dir ? dir + '/' + item.name : item.name;
    if (item.name.startsWith('.')) continue;
    // Link-preview images are fetched by messengers, never by the games.
    if (path === 'assets/share') continue;
    if (item.isDirectory() && (dir || ['assets', 'games'].includes(item.name))) {
      paths.push(...(await walk(path)));
    }
    if (item.isFile() && runtime.test(path) && !['sw.js', 'offline-files.js'].includes(path)) {
      paths.push(path);
    }
  }
  return paths;
}

const paths = (await walk('')).sort();
const html = await readFile(join(root, 'index.html'), 'utf8');
const catalogIds = (attribute) =>
  Array.from(html.matchAll(new RegExp(attribute + '="([a-z-]+)"', 'g')), (match) => match[1]);
const modes = catalogIds('data-mode');
const arcades = catalogIds('data-game-link');
const gameCount = new Set([...modes, ...arcades]).size;
if (!gameCount || gameCount !== modes.length + arcades.length)
  throw new Error('Missing or duplicate catalog entries');
const required = [
  'index.html',
  ...modes.flatMap((id) => [id + '.js', id + '.css']),
  'playroom.js',
  'manifest.webmanifest',
  ...arcades.flatMap((game) =>
    ['index.html', 'game.js', 'progress.js'].map((file) => 'games/' + game + '/' + file),
  ),
];
for (const path of required) {
  if (!paths.includes(path))
    throw new Error('The offline pack is missing ' + path + '. Synchronise the games first.');
}
const files = [];
for (const path of paths) {
  const bytes = await readFile(join(root, path));
  files.push([path, 'sha256-' + digest(bytes), bytes.length]);
}
const version = digest(JSON.stringify(files) + (await readFile(join(root, 'sw.js'), 'utf8'))).slice(0, 20);
const output =
  '// Generated by node scripts/update-offline.mjs\nconst OFFLINE_REVISION = ' +
  JSON.stringify(version) +
  ';\nconst OFFLINE_GAME_COUNT = ' +
  gameCount +
  ';\nconst OFFLINE_FILES = ' +
  JSON.stringify(files, null, 2) +
  ';\n';
const target = join(root, 'offline-files.js');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== output) {
    console.error('Run node scripts/update-offline.mjs to refresh the offline release.');
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
}
