// Platforms use world pixels. The tops of the flag and checkpoint extend up from their y.
const HEIGHT = 216;
const FLOOR = 174;

function course(id, title, ground, ledges, checkpointX, residents) {
  const width = ground.at(-1)[1];
  const platforms = ground.map(([x, end, y = FLOOR, kind = 'ground']) => ({
    x, y, w: end - x, h: kind === 'bridge' ? 9 : HEIGHT - y, kind,
  }));
  const bankAt = x => platforms.find(p => x >= p.x && x < p.x + p.w);
  const spawn = { x: 28, y: bankAt(28).y - 19 };
  const checkpoint = { x: checkpointX, y: bankAt(checkpointX).y };
  const flag = { x: width - 44, y: bankAt(width - 44).y };

  // Each patrol has a particular bank. Leave a full body's width before either edge.
  const enemies = residents.map(([type, x, radius]) => {
    const bank = bankAt(x);
    return { type, x, y: bank.y, minX: Math.max(bank.x + 3, x - radius),
      maxX: Math.min(bank.x + bank.w - 19, x + radius) };
  });
  const gems = [];
  // Breadcrumbs along the banks, with an extra gem above each gap to mark its jump.
  for (const [i, bank] of platforms.entries()) {
    for (let x = bank.x + 40; x < bank.x + bank.w - 23; x += 82) {
      if (x < 52 || Math.abs(checkpointX - x) < 16 || x >= flag.x - 12) continue;
      gems.push({ x, y: bank.y - 17 });
    }
    const next = platforms[i + 1], edge = bank.x + bank.w;
    if (next && next.x > edge) gems.push({ x: (edge + next.x) / 2, y: Math.min(bank.y, next.y) - 30 });
  }
  // Upper paths offer extra emeralds; the finish is reachable on the lower route.
  for (const [x, y, w] of ledges) {
    platforms.push({ x, y, w, h: 7, kind: 'ledge' });
    for (let gx = x + 13; gx < x + w - 6; gx += 31) gems.push({ x: gx, y: y - 12 });
  }
  return { id, title, width, height: HEIGHT, spawn, platforms, gems, enemies, checkpoint, flag };
}

